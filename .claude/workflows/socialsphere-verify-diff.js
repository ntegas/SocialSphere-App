export const meta = {
  name: 'socialsphere-verify-diff',
  description: 'Проверка diff SocialSphere по 4 известным линиям провала: данные/миграции, i18n, хардкод/переиспользование, чек-лист живой проверки',
  whenToUse: 'После того как реализация в ss-v1 готова (есть незакоммиченный diff), перед тем как считать задачу завершённой.',
  phases: [
    { title: 'Verify', detail: 'четыре независимых проверяющих луча по текущему git diff' },
    { title: 'Critique', detail: 'проверка самих проверяющих — не халтурили ли, не пропустили ли явное' },
  ],
}

const context = (args && args.context) ? args.context : (typeof args === 'string' ? args : '')

const CONTEXT = `Проект: SocialSphere, репозиторий C:\\ss, модуль ss-v1, пакет com.aistudio.socialsphere.crmlxb. Проверяешь ТЕКУЩИЙ незакоммиченный diff (запусти сам: git -C C:\\ss diff, при необходимости git -C C:\\ss status). ${context ? ('Контекст задачи от автора изменений: ' + context) : ''}`

phase('Verify')
const lenses = [
  {
    key: 'data-safety',
    prompt: `${CONTEXT}\n\nПроверь diff на риски потери данных: (1) если менялась @Database(version=N) в SocialsphereDatabase.kt — есть ли полная цепочка MIGRATION_(N-1)_N без пропусков, и нет ли fallbackToDestructiveMigration() (его быть не должно вообще); (2) если менялись data class сущностей (Contact/Note/CalendarItem/...) и есть места, где объект пересобирается — используется ли copy() от оригинала, а не конструктор с нуля (конструктор с нуля стирает не перечисленные поля); (3) если добавлено новое поле в сущность — грепни по всей кодовой базе, добавлено ли оно во ВСЕ места пересборки (импорт контактов, слияние дублей, конвертация контакт→компания). Верни конкретные находки в формате "файл:строка — проблема", либо явно напиши "проблем не найдено".`,
  },
  {
    key: 'i18n',
    prompt: `${CONTEXT}\n\nПроверь diff на локализацию: любая новая пользовательская строка (Text(...), label=..., contentDescription=..., subtitle=... и т.п.) должна идти через stringResource(R.string....), НЕ строковым литералом на русском/английском. Если в diff добавлены новые <string name="..."> в values/strings.xml — сверь, что те же имена ключей добавлены и в values-en/strings.xml, и в values-el/strings.xml (сравни списки имён). Верни конкретные находки "файл:строка — проблема", либо "проблем не найдено".`,
  },
  {
    key: 'reuse-hardcode',
    prompt: `${CONTEXT}\n\nПроверь diff на дублирование и немотивированный хардкод: не завёлся ли новый локальный список/enum/палитра, дублирующий уже существующий общий (например AureliaAvatars.gradients, SocialShape, AureliaSheet/AureliaFormSheet/AureliaPickerSheet, PersistedMutableState). Не захардкожены ли категории/значения, для которых стоило поискать индустриальный стандарт вместо решения "из головы". Верни конкретные находки "файл:строка — проблема", либо "проблем не найдено".`,
  },
  {
    key: 'live-verification-checklist',
    prompt: `${CONTEXT}\n\nТы не имеешь доступа к эмулятору — твоя задача НЕ проверить вживую, а составить точный чек-лист того, что нужно проверить на эмуляторе по этому diff, чтобы ничего не забыли: конкретные экраны, конкретные действия ("открыть карточку контакта X, тапнуть Y, убедиться что Z"), и если diff касается UI-текста — на каких именно языках это нужно перепроверить. Верни короткий пронумерованный чек-лист, не общие слова.`,
  },
]

const findings = await parallel(lenses.map(l => () =>
  agent(l.prompt, { label: l.key, phase: 'Verify' }).then(r => ({ key: l.key, report: r }))
))

phase('Critique')
const rawFindings = findings.filter(Boolean)
const combinedReports = rawFindings.map(f => `### ${f.key}\n${f.report}`).join('\n\n')

const critique = await agent(
  `${CONTEXT}\n\nЧетыре проверяющих агента только что независимо проверили diff и вернули эти отчёты:\n\n${combinedReports}\n\nТвоя работа — проверить САМИХ проверяющих, не оригинальный код. По умолчанию подозревай, что кто-то из них мог схалтурить (например написать "проблем не найдено" не проверив реально, или дать общий совет вместо конкретной находки). Сделай сам, независимо: 1) запусти git -C C:\\ss diff и прочитай его целиком; 2) для каждого из 4 отчётов реши — похоже ли, что агент реально прочитал diff и погрепал кодовую базу (есть ссылки на конкретные строки/файлы, которых нет в самом diff — значит грепал шире), или ответ выглядит шаблонным/поверхностным; 3) если у тебя самого при чтении diff возникло подозрение, которое ни один из 4 агентов не поднял (данные/локализация/дублирование) — прямо укажи его отдельно, это не их вина, а пропуск. Верни: по каждому из 4 ключей (data-safety/i18n/reuse-hardcode/live-verification-checklist) — вердикт "похоже на честную проверку" или "похоже на шаблонный ответ, перепроверь вручную" с обоснованием; плюс отдельный список того, что упущено всеми четырьмя, если такое есть.`,
  { label: 'critique', phase: 'Critique' }
)

log('Проверка diff и критика проверяющих завершены')
const summary = combinedReports + `\n\n## critique (проверка проверяющих)\n${critique}`
return { summary, findings: rawFindings, critique }
