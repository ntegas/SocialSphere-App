package com.aistudio.socialsphere.crmlxb.utils

import com.aistudio.socialsphere.crmlxb.model.Contact

/**
 * Номер, который приложение выбирает САМО, когда действие не привязано к
 * конкретному номеру (кнопки «Позвонить»/«Написать» в шапке карточки и в
 * Шпаргалке, телефон для кнопок напоминания): основной (isPrimary), иначе первый.
 *
 * Одно определение вместо копий: раньше «Позвонить» брал основной номер, а
 * запасной SMS в «Написать» — просто первый, и для одного контакта два действия
 * уходили на разные номера. Нажатие на конкретный номер в списке телефонов
 * (вкладка «Общение») этим правилом НЕ перенаправляется — там номер выбрал человек.
 */
fun Contact.preferredPhoneNumber(): String? =
    (phones.firstOrNull { it.isPrimary } ?: phones.firstOrNull())?.number
